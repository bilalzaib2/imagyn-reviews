export interface EmailSendRequest {
  to: string;
  subject: string;
  html: string;
  text: string;
  // Display name shown alongside the verified From address (e.g. "Coastal Threads
  // <reviews@notifications.imagyn.co>") — lets a customer-facing send (review requests,
  // reminders) read as coming from the merchant's own store, not a generic "Imagyn Reviews"
  // identity, without requiring per-merchant domain verification (a real Resend/provider
  // constraint — see resend.server.ts). Omitted entirely for Imagyn's own merchant-facing
  // notifications (e.g. ReviewHeldEmail), which should keep the Imagyn identity as-is.
  fromName?: string;
  // Merchant-configurable reply-to (Email Studio's "Reply-to" field, email.shared.ts's
  // EmailTemplateContent.replyToEmail) — real customer replies land in an inbox the merchant
  // actually reads, without requiring per-merchant sending-domain verification (the From
  // address itself stays on Imagyn's verified domain regardless — see fromName's own comment
  // for why that's a real Resend/deliverability constraint, not a missing feature).
  replyTo?: string;
  // Provider-level metadata echoed back on delivery webhooks (see resend.server.ts and
  // webhooks.resend.tsx) — optional and provider-specific (a provider without tag support
  // just ignores it), so this stays here rather than forcing every EmailProvider
  // implementation to support it.
  tags?: Record<string, string>;
  /**
   * De-duplicates a retried send AT THE PROVIDER, so the same logical email cannot go out twice
   * even if this app asks twice.
   *
   * Why it exists: the scheduler claims a row before sending, and recovers a claim that was
   * never completed (reviewRequestScheduler.server.ts). If a worker dies in the gap between the
   * provider accepting the email and the terminal status write landing, the email was delivered
   * but the row still looks unsent — and recovery would send it again. A stable key turns that
   * second attempt into a no-op at the provider instead of a second email in the customer's
   * inbox.
   *
   * Resend implements this as the `Idempotency-Key` header: a repeat with the same key returns
   * the original response without resending, and keys are retained for 24 hours — far longer
   * than the 15-minute recovery lease. A provider without an equivalent simply ignores this
   * field, which is why it lives here rather than in the Resend adapter's own signature.
   *
   * IMPORTANT: a key identifies one intended delivery, never its content. Resend answers
   * `409 invalid_idempotent_request` when the same key arrives with a DIFFERENT payload, so a
   * key derived from the body would turn a legitimate retry into an error. Callers key on the
   * request token instead: stable across retries of a single attempt, and regenerated by
   * resendRequest when a merchant deliberately sends again.
   */
  idempotencyKey?: string;
}

export interface EmailSendResult {
  id: string;
}

// Every channel (Email today; SMS/WhatsApp later) gets its own narrow provider interface
// here rather than one unified send(message) shape — an email needs subject/html/text, an
// SMS needs a phone number and a text body, and forcing those through one signature would
// leak one channel's concerns into another's. review-request.server.ts, the only caller,
// depends on EmailProvider and never on a specific vendor's request format — that's what
// makes switching vendors a config change (EMAIL_PROVIDER env var) instead of a code change.
// UI components never import from this directory at all. Mirrors app/services/ai/types.ts.
export interface EmailProvider {
  readonly name: string;
  sendEmail(request: EmailSendRequest): Promise<EmailSendResult>;
}

export class NotificationProviderError extends Error {
  constructor(
    message: string,
    public readonly provider: string,
  ) {
    super(message);
    this.name = "NotificationProviderError";
  }
}
